<#
.SYNOPSIS
  Tests the PROPOSED consolidated migration on a throwaway LOCAL Supabase stack.

.DESCRIPTION
  Safety design:
    * Works only in a brand-new temporary folder under %TEMP%.
    * That folder is never linked to a hosted project (no `supabase link`).
    * Runs only: supabase init, supabase start, supabase status, supabase stop.
    * Never runs: db push, db reset, link, migration repair, or any remote command.
    * Does not modify this repository.
  Requirements: Docker Desktop running; PowerShell 7 recommended; the repo's
  supabase CLI dev dependency (node_modules). Local stack passwords default to 'postgres'.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\db\local-supabase-stack-test.ps1
#>
[CmdletBinding()]
param(
    [switch]$KeepRunning   # leave the local stack up for inspection
)

$ErrorActionPreference = 'Stop'
$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$Migrations = @(
    'supabase\migrations\20261103142214_initial_chromite_schema.sql',
    'supabase\migrations\20261103170000_chromite_least_privilege_permissions.sql',
    'supabase\migrations-proposed\20261104090000_consolidated_grants_rls_superadmin_audit.sql'
)
$Rollback = 'supabase\migrations-proposed\20261104090000_consolidated_grants_rls_superadmin_audit.ROLLBACK.sql'
$Forward  = $Migrations[2]
$Probe    = 'tools\db\local_stack_probe.sql'

function Step($m) { Write-Host "`n== $m" -ForegroundColor Cyan }

# --- Preconditions --------------------------------------------------------
docker info *> $null
if ($LASTEXITCODE -ne 0) { throw 'Docker Desktop is not running.' }

$Cli = Join-Path $RepoRoot 'node_modules\.bin\supabase.cmd'
if (-not (Test-Path $Cli)) { throw "Supabase CLI not found at $Cli (run: npm install)" }

foreach ($f in $Migrations + $Rollback + $Probe) {
    if (-not (Test-Path (Join-Path $RepoRoot $f))) { throw "Missing $f" }
}

$Work = Join-Path $env:TEMP ('chromite-localstack-' + (Get-Date -Format 'yyyyMMdd-HHmmss'))
New-Item -ItemType Directory -Path $Work | Out-Null
Step "Temporary project: $Work"

Push-Location $Work
$started = $false
try {
    Step 'supabase init (local only)'
    & $Cli init | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'supabase init failed' }

    # Guard: this folder must not be linked to any hosted project.
    if (Test-Path 'supabase\.temp\project-ref') { throw 'Refusing: temp project is linked to a hosted project.' }

    $ProjectId = (Select-String -Path 'supabase\config.toml' -Pattern '^\s*project_id\s*=\s*"([^"]+)"').Matches[0].Groups[1].Value
    New-Item -ItemType Directory -Force -Path 'supabase\migrations' | Out-Null
    foreach ($f in $Migrations) { Copy-Item (Join-Path $RepoRoot $f) 'supabase\migrations\' }

    Step 'supabase start (applies the 3 migrations to the local database)'
    & $Cli start | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'supabase start failed' }
    $started = $true

    $Db = "supabase_db_$ProjectId"
    function Psql([string]$File, [string]$User = 'supabase_admin') {
        Get-Content -Raw (Join-Path $RepoRoot $File) |
            docker exec -i -e PGPASSWORD=postgres $Db psql -U $User -d postgres -v ON_ERROR_STOP=1 -q
        if ($LASTEXITCODE -ne 0) { throw "psql failed: $File" }
    }

    Step 'SQL probe after forward migration'
    Psql $Probe

    Step 'REST check: anon reads public views through PostgREST'
    $status = & $Cli status -o json | ConvertFrom-Json
    $api = $status.API_URL
    # LOCAL stack demo key only (generated by `supabase start`), never a hosted credential.
    $anon = if ($status.PUBLISHABLE_KEY) { $status.PUBLISHABLE_KEY } else { $status.ANON_KEY }
    foreach ($v in 'public_mines','public_laboratories','public_sampling_providers') {
        $r = Invoke-WebRequest -UseBasicParsing -Uri "$api/rest/v1/$v`?select=id&limit=1" -Headers @{ apikey = $anon }
        Write-Host "PASS: REST $v -> HTTP $($r.StatusCode)"
    }

    Step 'Rollback, verify defect state returns, then re-apply forward'
    Psql $Rollback 'postgres'
    $out = 'SET ROLE anon; SELECT count(*) FROM public.public_mines;' |
        docker exec -i -e PGPASSWORD=postgres $Db psql -U supabase_admin -d postgres 2>&1
    if (($out | Out-String) -notmatch 'permission denied') { throw 'Rollback did not restore pre-migration state' }
    Write-Host 'PASS: rollback restored pre-migration permissions'
    Psql $Forward 'postgres'
    Psql $Probe
    Write-Host "`nLOCAL SUPABASE STACK TEST PASSED" -ForegroundColor Green
}
finally {
    if ($started -and -not $KeepRunning) {
        Step 'supabase stop --no-backup (local containers only)'
        & $Cli stop --no-backup | Out-Host
    }
    Pop-Location
    Write-Host "Temporary folder kept for review: $Work"
}
